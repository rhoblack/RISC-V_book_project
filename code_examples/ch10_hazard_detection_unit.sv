// ============================================================================
// 해저드 감지 유닛 (Hazard Detection Unit)
// Chapter 10 — 데이터 해저드와 포워딩
// RISC-V 프로세서 설계 완전정복
// ============================================================================
// Load-Use 해저드를 감지하여 1사이클 스톨 신호 생성
// 스톨 시: PC 홀드, IF/ID 홀드, ID/EX 버블(flush) 삽입
// ============================================================================

`timescale 1ns / 1ps

module hazard_detection_unit (
   // --- ID/EX 파이프라인 레지스터 정보 ---
   input  logic       id_ex_mem_read,   // ID/EX: 메모리 읽기 명령어 (lw/lh/lb 등)
   input  logic [4:0] id_ex_rd,         // ID/EX: 목적지 레지스터

   // --- IF/ID 파이프라인 레지스터 정보 ---
   input  logic [4:0] if_id_rs1,        // IF/ID: 소스 레지스터 1
   input  logic [4:0] if_id_rs2,        // IF/ID: 소스 레지스터 2

   // --- 스톨 제어 신호 ---
   output logic       pc_en,            // PC 인에이블 (0: 홀드)
   output logic       if_id_en,         // IF/ID 레지스터 인에이블 (0: 홀드)
   output logic       id_ex_flush       // ID/EX 레지스터 플러시 (1: 버블 삽입)
);

   // =======================================================================
   // Load-Use 해저드 감지 로직
   // =======================================================================
   // 감지 조건:
   //   1) 현재 EX 스테이지의 명령어가 메모리 읽기(Load) 명령어
   //   2) Load의 목적지 레지스터(rd)가 x0이 아님
   //   3) Load의 rd가 다음 명령어(ID 스테이지)의 rs1 또는 rs2와 일치
   //
   // 이 조건이 충족되면:
   //   - 로드 데이터는 MEM 스테이지 끝에서야 확정됨
   //   - 후속 명령어의 EX 스테이지에서 해당 값이 필요함
   //   - 1사이클 스톨 후 MEM-EX 포워딩으로 해결 가능
   // =======================================================================

   logic load_use_hazard;

   always_comb begin
      load_use_hazard = id_ex_mem_read &&
                        (id_ex_rd != 5'b0) &&
                        ((id_ex_rd == if_id_rs1) ||
                         (id_ex_rd == if_id_rs2));
   end

   // =======================================================================
   // 스톨 신호 생성
   // =======================================================================
   always_comb begin
      if (load_use_hazard) begin
         // 스톨 상태: 파이프라인 앞단 동결 + EX에 버블 삽입
         pc_en       = 1'b0;   // PC 값 유지 (같은 명령어 재인출)
         if_id_en    = 1'b0;   // IF/ID 레지스터 유지 (같은 명령어 재해독)
         id_ex_flush = 1'b1;   // ID/EX에 NOP 삽입 (버블)
      end
      else begin
         // 정상 상태: 파이프라인 진행
         pc_en       = 1'b1;
         if_id_en    = 1'b1;
         id_ex_flush = 1'b0;
      end
   end

endmodule
