// ============================================================================
// 모듈명  : led_blinker_tb
// 파일명  : ch01_led_blinker_tb.sv
// 설명    : led_blinker 모듈의 테스트벤치
//           시뮬레이션에서 LED 패턴 순환과 리셋 동작을 검증
// 작성 기준: SystemVerilog IEEE 1800-2017
// ============================================================================

`timescale 1ns / 1ps

module led_blinker_tb;

   // -----------------------------------------------------------------------
   // 테스트벤치 신호 선언
   // -----------------------------------------------------------------------
   logic       clk;
   logic       rst_n;
   logic [3:0] led;

   // -----------------------------------------------------------------------
   // 시뮬레이션용 파라미터 (빠른 검증을 위해 카운터 최대값을 작게 설정)
   // -----------------------------------------------------------------------
   localparam int unsigned SIM_MAX_COUNT = 5;  // 5 사이클마다 틱 발생

   // -----------------------------------------------------------------------
   // DUT (Design Under Test) 인스턴스화
   // -----------------------------------------------------------------------
   led_blinker dut (
      .clk   (clk),
      .rst_n (rst_n),
      .led   (led)
   );

   // 시뮬레이션 목적으로 DUT 내부 카운터 최대값을 오버라이드
   // 주의: 실제 합성 시에는 이 방법을 사용하지 않음
   // defparam dut.MAX_COUNT = SIM_MAX_COUNT - 1;  // 필요 시 활성화

   // -----------------------------------------------------------------------
   // 클록 생성: 100MHz (주기 10ns)
   // -----------------------------------------------------------------------
   initial begin
      clk = 1'b0;
      forever #5 clk = ~clk;  // 5ns 반주기 → 10ns 주기 → 100MHz
   end

   // -----------------------------------------------------------------------
   // 테스트 시나리오
   // -----------------------------------------------------------------------
   initial begin
      // 파형 덤프 설정 (VCS/Vivado 시뮬레이터 호환)
      $dumpfile("led_blinker_tb.vcd");
      $dumpvars(0, led_blinker_tb);

      // ---- 테스트 1: 리셋 동작 확인 ----
      $display("=== 테스트 1: 리셋 동작 확인 ===");
      rst_n = 1'b0;           // 리셋 인가 (능동 저)
      #100;                    // 100ns 동안 리셋 유지

      // 리셋 중 LED 상태 확인
      assert (led == 4'b0001)
         $display("[PASS] 리셋 중 LED 초기값 = %b", led);
      else
         $error("[FAIL] 리셋 중 LED 값 = %b, 기대값 = 0001", led);

      // ---- 테스트 2: 리셋 해제 후 정상 동작 ----
      $display("\n=== 테스트 2: 리셋 해제 후 정상 동작 ===");
      rst_n = 1'b1;           // 리셋 해제
      $display("리셋 해제 시각: %0t ns", $time);

      // 충분한 시간 동안 시뮬레이션 실행
      // MAX_COUNT가 기본값(50,000,000)일 경우 매우 오래 걸리므로
      // 실제 시뮬레이션 시에는 MAX_COUNT를 작은 값으로 변경하여 테스트
      #1000;

      // ---- 테스트 3: 리셋 재인가 ----
      $display("\n=== 테스트 3: 리셋 재인가 ===");
      rst_n = 1'b0;
      #50;

      assert (led == 4'b0001)
         $display("[PASS] 재리셋 후 LED 초기값 = %b", led);
      else
         $error("[FAIL] 재리셋 후 LED 값 = %b, 기대값 = 0001", led);

      rst_n = 1'b1;
      #500;

      // ---- 테스트 완료 ----
      $display("\n=== 테스트 완료 ===");
      $display("모든 테스트 시나리오 실행 완료");
      $display("파형 파일: led_blinker_tb.vcd 에서 상세 동작을 확인하십시오.");
      $finish;
   end

   // -----------------------------------------------------------------------
   // LED 변화 모니터링: LED 값이 변할 때마다 자동 출력
   // -----------------------------------------------------------------------
   always @(led) begin
      $display("[%0t ns] LED 변화 감지: led = %b", $time, led);
   end

   // -----------------------------------------------------------------------
   // 시뮬레이션 타임아웃 방지
   // -----------------------------------------------------------------------
   initial begin
      #10_000_000;  // 10ms 시뮬레이션 제한
      $display("[TIMEOUT] 시뮬레이션 시간 초과 — 강제 종료");
      $finish;
   end

endmodule
