# =============================================================================
# 버블 정렬 (Bubble Sort) — RV32I 어셈블리
# Chapter 12 검증용 테스트 프로그램
#
# 기능: 데이터 메모리의 8개 정수를 오름차순 정렬
# 해저드 검증 포인트:
#   - Load-Use 해저드 (LW 직후 비교)
#   - 데이터 포워딩 (연속 ADD/SUB)
#   - 제어 해저드 (BEQ/BNE 분기)
#   - WB-ID 포워딩 (레지스터 충돌)
# =============================================================================

.text
.globl _start

_start:
   # ----- 초기 설정 -----
   la    a0, array         # a0 = 배열 시작 주소
   li    a1, 8             # a1 = 배열 길이 (n)

   # ----- 외부 루프 (i = n-1 ~ 1) -----
outer_loop:
   addi  a1, a1, -1        # a1 = n - 1 (남은 비교 횟수)
   beqz  a1, done          # n-1 == 0이면 정렬 완료
   mv    a2, a0            # a2 = 현재 비교 포인터 (배열 시작)
   mv    a3, a1            # a3 = 내부 루프 카운터 (j)

   # ----- 내부 루프 -----
inner_loop:
   lw    t0, 0(a2)         # t0 = array[j]    ← Load-Use 해저드 발생
   lw    t1, 4(a2)         # t1 = array[j+1]  ← Load-Use 해저드 발생
   ble   t0, t1, no_swap   # t0 <= t1이면 교환 불필요 → 제어 해저드

   # ----- 교환 (swap) -----
   sw    t1, 0(a2)         # array[j] = t1
   sw    t0, 4(a2)         # array[j+1] = t0

no_swap:
   addi  a2, a2, 4         # 포인터 이동  ← 데이터 포워딩 (a2 연속 사용)
   addi  a3, a3, -1        # 내부 카운터 감소
   bnez  a3, inner_loop    # j != 0이면 계속 → 제어 해저드

   j     outer_loop        # 외부 루프 반복

done:
   ecall                   # 프로그램 종료

# ----- 정렬할 데이터 배열 -----
.data
array:
   .word 64, 25, 12, 22, 11, 90, 33, 47
