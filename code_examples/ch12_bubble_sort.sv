// ============================================================================
// ch12_bubble_sort.sv
// Chapter 12 — 구조적 해저드와 파이프라인 완성
// RISC-V 프로세서 설계 완전정복
// ============================================================================
// 버블정렬 RISC-V RV32I 어셈블리 → 기계어 변환
// 대상 배열: [64, 5, 66, 30, 88, 17, 42, 9] → [5, 9, 17, 30, 42, 64, 66, 88]
//
// 레지스터 할당:
//   x10 (a0) = 배열 베이스 주소 (DMEM 바이트 주소)
//   x11 (a1) = 외부 루프 카운터 i
//   x12 (a2) = 내부 루프 카운터 j
//   x13 (a3) = N = 8 (배열 크기)
//   x14 (a4) = 임시 값 a[j]
//   x15 (a5) = 임시 값 a[j+1]
//   x16 (a6) = N-1 (임시)
//   x17 (a7) = N-1-i (내부 루프 한계)
//   x18 (s2) = j*4 (바이트 오프셋)
//   x19 (s3) = &a[j] (주소)
//
// 어셈블리 소스:
// ─────────────────────────────────────────────────────────────────────────────
// bubble_sort:
//   li   x13, 8          # N = 8                  (ADDI x13, x0, 8)
//   li   x10, 0          # 배열 베이스 = 0         (ADDI x10, x0, 0)
//   li   x11, 0          # i = 0                  (ADDI x11, x0, 0)
//
// outer_loop:
//   addi x16, x13, -1    # x16 = N-1 = 7
//   bge  x11, x16, done  # if i >= N-1, 종료
//   li   x12, 0          # j = 0
//
// inner_loop:
//   sub  x17, x16, x11   # x17 = N-1-i (내부 루프 한계)
//   bge  x12, x17, outer_next  # if j >= N-1-i, 외부 루프 증가
//   slli x18, x12, 2     # x18 = j*4 (바이트 오프셋)
//   add  x19, x10, x18   # x19 = &a[j]
//   lw   x14, 0(x19)     # x14 = a[j]
//   lw   x15, 4(x19)     # x15 = a[j+1]
//   ble  x14, x15, no_swap  # if a[j] <= a[j+1], 교환 불필요
//   sw   x15, 0(x19)     # a[j] = a[j+1]    (교환)
//   sw   x14, 4(x19)     # a[j+1] = a[j]    (교환)
//
// no_swap:
//   addi x12, x12, 1     # j++
//   jal  x0, inner_loop  # inner_loop로 점프
//
// outer_next:
//   addi x11, x11, 1     # i++
//   jal  x0, outer_loop  # outer_loop로 점프
//
// done:
//   addi x0, x0, 0       # NOP (종료 마커)
// ─────────────────────────────────────────────────────────────────────────────
//
// 기계어 인코딩 (PC=0x000부터 시작, 바이트 주소):
//   주소    기계어       명령어
//   0x000   00800693    ADDI x13, x0, 8
//   0x004   00000513    ADDI x10, x0, 0
//   0x008   00000593    ADDI x11, x0, 0
//   [outer_loop: PC=0x00C]
//   0x00C   FFF68813    ADDI x16, x13, -1
//   0x010   0305DE63    BGE  x11, x16, done (offset=+60=0x3C → PC=0x04C)  [수정: funct3=101=BGE]
//   0x014   00000613    ADDI x12, x0, 0
//   [inner_loop: PC=0x018]
//   0x018   40B808B3    SUB  x17, x16, x11
//   0x01C   03165463    BGE  x12, x17, outer_next (offset=+40=0x28 → PC=0x044)  [수정: funct3=101=BGE]
//   0x020   00261913    SLLI x18, x12, 2
//   0x024   012509B3    ADD  x19, x10, x18  [수정: rd=x19(10011), 이전 01250933은 rd=x18(오류)]
//   0x028   0009A703    LW   x14, 0(x19)
//   0x02C   0049A783    LW   x15, 4(x19)
//   0x030   00E7D663    BGE  x15, x14, no_swap (BLE a<=b → BGE b,a; offset=+12)
//   0x034   00F9A023    SW   x15, 0(x19)
//   0x038   00E9A223    SW   x14, 4(x19)
//   [no_swap: PC=0x03C]
//   0x03C   00160613    ADDI x12, x12, 1
//   0x040   FD9FF06F    JAL  x0, inner_loop (offset=-40 → 0x018)
//   [outer_next: PC=0x044]
//   0x044   00158593    ADDI x11, x11, 1
//   0x048   FC5FF06F    JAL  x0, outer_loop (offset=-60=0xFFFFFFC4 → 0x00C)  [수정: -60이 정확한 값]
//   [done: PC=0x04C]
//   0x04C   00000013    ADDI x0, x0, 0 (NOP)
// ─────────────────────────────────────────────────────────────────────────────
//
// [중요] 위 기계어는 설명용 근사값입니다.
// 실제 시뮬레이션에서는 GNU RISC-V 어셈블러(riscv64-unknown-elf-as)로
// 정확한 기계어를 생성한 후 $readmemh로 로딩하십시오.
//
// 빠른 시뮬레이션: ch12_pipeline_complete_tb.sv의 테스트벤치가
// dut.u_imem.mem 배열에 직접 기계어를 설정합니다.
// 데이터 메모리(DMEM)도 테스트벤치에서 직접 초기화합니다.
// ============================================================================

// 이 파일은 참고용 어셈블리 주석 파일입니다.
// 실제 실행을 위한 기계어는 ch12_pipeline_complete_tb.sv에 포함되어 있습니다.

// $readmemh 형식 예시 (bubble_sort.hex):
// 파일 내용 (각 줄이 1 워드 = 32비트):
//   00800693   // [0x000] ADDI x13, x0,  8     (N=8)
//   00000513   // [0x004] ADDI x10, x0,  0     (배열 베이스=0)
//   00000593   // [0x008] ADDI x11, x0,  0     (i=0)
//   FFF68813   // [0x00C] ADDI x16, x13, -1   (N-1)
//   0305DE63   // [0x010] BGE  x11, x16, done  (funct3=101=BGE, offset=+60)
//   00000613   // [0x014] ADDI x12, x0,  0     (j=0)
//   40B808B3   // [0x018] SUB  x17, x16, x11   (N-1-i)
//   03165463   // [0x01C] BGE  x12, x17, outer_next  (funct3=101=BGE, offset=+40)
//   00261913   // [0x020] SLLI x18, x12, 2     (j*4)
//   012509B3   // [0x024] ADD  x19, x10, x18   (&a[j], rd=x19)
//   0009A703   // [0x028] LW   x14, 0(x19)     (a[j])
//   0049A783   // [0x02C] LW   x15, 4(x19)     (a[j+1])
//   00E7D663   // [0x030] BGE  x15, x14, no_swap (a[j]<=a[j+1] 시 skip)
//   00F9A023   // [0x034] SW   x15, 0(x19)     (a[j]=a[j+1])
//   00E9A223   // [0x038] SW   x14, 4(x19)     (a[j+1]=a[j])
//   00160613   // [0x03C] ADDI x12, x12, 1     (j++)
//   FD9FF06F   // [0x040] JAL  x0, inner_loop  (-40바이트)
//   00158593   // [0x044] ADDI x11, x11, 1     (i++)
//   FC5FF06F   // [0x048] JAL  x0, outer_loop  (-60바이트 근사값)
//   00000013   // [0x04C] ADDI x0, x0, 0       (NOP/done)
