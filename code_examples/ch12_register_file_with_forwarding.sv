// Chapter 12 — 구조적 해저드와 파이프라인 완성
// RISC-V 프로세서 설계 완전정복
// ============================================================================
// ch04_register_file.sv 기반에 WB-ID 포워딩(Read-During-Write) 추가
//
// 설계 결정:
//   - 비동기 읽기 (Asynchronous Read) — FPGA에서 LUTRAM 추론
//   - 동기 쓰기   (Synchronous Write) — posedge clk에서 기록
//   - x0 레지스터: 쓰기 무시, 항상 0 반환
//   - WB-ID 포워딩: WB 스테이지(사이클 N)가 쓰는 동시에
//                   ID 스테이지(사이클 N)가 같은 레지스터를 읽을 때
//                   레지스터 파일 내부에서 새 값을 즉시 반환
//
// WB-ID 포워딩 조건:
//   reg_w_en && (rd_addr != 5'b0) && (rd_addr == rs1_addr 또는 rs2_addr)
//
// Ch10의 forwarding_unit은 수정하지 않습니다.
// 이 모듈이 WB-ID 포워딩을 독립적으로 처리합니다.
// ============================================================================

`timescale 1ns / 1ps

module register_file (
   input  logic        clk,          // 시스템 클록
   input  logic        rst_n,        // 비동기 리셋 (액티브 로우)

   // --- 읽기 포트 1 (비동기 + WB-ID 포워딩 포함) ---
   input  logic [4:0]  rs1_addr,     // 소스 레지스터 1 주소 (instr[19:15])
   output logic [31:0] rs1_data,     // 소스 레지스터 1 데이터 (포워딩 포함)

   // --- 읽기 포트 2 (비동기 + WB-ID 포워딩 포함) ---
   input  logic [4:0]  rs2_addr,     // 소스 레지스터 2 주소 (instr[24:20])
   output logic [31:0] rs2_data,     // 소스 레지스터 2 데이터 (포워딩 포함)

   // --- 쓰기 포트 (동기, WB 스테이지에서 연결) ---
   input  logic [4:0]  rd_addr,      // 목적지 레지스터 주소 (MEM/WB.rd)
   input  logic [31:0] rd_data,      // 기록할 데이터 (WB 스테이지 wb_data)
   input  logic        reg_w_en      // 쓰기 인에이블 (MEM/WB.reg_w_en)
);

   // =========================================================================
   // 32개 x 32비트 레지스터 배열
   // =========================================================================
   logic [31:0] rf [0:31];

   // =========================================================================
   // 동기 쓰기 로직
   // x0 레지스터는 항상 0이므로 쓰기를 무시합니다.
   // 리셋 시 모든 레지스터를 0으로 초기화합니다.
   // =========================================================================
   always_ff @(posedge clk or negedge rst_n) begin
      if (!rst_n) begin
         // 비동기 리셋: 모든 레지스터를 0으로 초기화
         for (int i = 0; i < 32; i++) begin
            rf[i] <= 32'b0;
         end
      end
      else if (reg_w_en && (rd_addr != 5'b0)) begin
         // x0이 아닌 레지스터에만 쓰기 수행
         rf[rd_addr] <= rd_data;
      end
   end

   // =========================================================================
   // 비동기 읽기 로직 — WB-ID 포워딩 포함
   // =========================================================================
   // [포워딩 조건]
   //   - reg_w_en: WB 스테이지가 현재 사이클에 레지스터를 쓰려 한다
   //   - rd_addr != 5'b0: x0에 대한 포워딩은 의미 없으므로 제외
   //   - rd_addr == rs1_addr: WB의 목적지와 ID의 소스 1이 같다
   //
   // [포워딩 없을 때]
   //   LUTRAM(비동기 읽기)은 합성기에 따라 Write-First 또는 Read-First로
   //   추론될 수 있습니다. 명시적 포워딩 로직으로 합성기 의존성을 제거합니다.
   //
   // [x0 특수 처리]
   //   rs1_addr == 5'b0이면 포워딩 조건이 성립하더라도 0 반환
   //   (rd_addr != 5'b0 조건에서 포워딩 자체가 막힘)
   //   rs1_addr == 5'b0이고 rd_addr != 0인 경우: rf[0] = 0이므로 문제없음
   // =========================================================================

   // 소스 레지스터 1 읽기 (WB-ID 포워딩 적용)
   assign rs1_data = (reg_w_en && (rd_addr != 5'b0) && (rd_addr == rs1_addr))
                     ? rd_data         // WB-ID 포워딩: WB가 쓰는 값을 즉시 반환
                     : rf[rs1_addr];   // 일반 읽기: 레지스터 파일에서 읽기

   // 소스 레지스터 2 읽기 (WB-ID 포워딩 적용)
   assign rs2_data = (reg_w_en && (rd_addr != 5'b0) && (rd_addr == rs2_addr))
                     ? rd_data         // WB-ID 포워딩: WB가 쓰는 값을 즉시 반환
                     : rf[rs2_addr];   // 일반 읽기: 레지스터 파일에서 읽기

   // x0 보호는 rf[0]=0 초기화와 rd_addr != 5'b0 쓰기 방지로 자동 처리됩니다.
   // rs1_addr == 0이면 rf[0] = 0을 반환합니다.

endmodule
