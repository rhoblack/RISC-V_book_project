// ============================================================================
// 중간 레지스터 4종 (Intermediate Pipeline Registers)
// Chapter 07 — 멀티사이클 데이터패스
// RISC-V 프로세서 설계 완전정복
// ============================================================================
// 목적: 각 사이클 경계에서 데이터를 보존하는 4종 레지스터 독립 구현
// 포함: IR (명령어 레지스터), MDR (메모리 데이터 레지스터), A 레지스터, B 레지스터
// 비동기 리셋(rst_n) 포함
// ============================================================================

`timescale 1ns / 1ps

module intermediate_regs (
   input  logic        clk,            // 시스템 클럭
   input  logic        rst_n,          // 비동기 리셋 (액티브 로우)

   // --- 명령어 레지스터 (IR) 제어 ---
   input  logic        ir_write,       // IR 쓰기 인에이블 (IF 단계에서만 1)
   input  logic [31:0] mem_data_out,   // 메모리에서 읽은 원시 데이터

   // --- A/B 레지스터 입력 ---
   input  logic [31:0] rs1_data,       // 레지스터 파일에서 읽은 rs1 데이터
   input  logic [31:0] rs2_data,       // 레지스터 파일에서 읽은 rs2 데이터

   // --- 출력 ---
   output logic [31:0] ir_reg,         // 명령어 레지스터 출력 (명령어 필드 추출용)
   output logic [31:0] mdr_reg,        // 메모리 데이터 레지스터 출력 (LW 결과)
   output logic [31:0] a_reg,          // A 레지스터 출력 (ALU 입력 A)
   output logic [31:0] b_reg           // B 레지스터 출력 (ALU 입력 B 또는 SW 데이터)
);

   // =========================================================================
   // 1. 명령어 레지스터 (IR — Instruction Register)
   // =========================================================================
   // 역할: IF 단계에서 메모리가 반환한 명령어를 이후 사이클(ID, EX, WB)에서도
   //       안정적으로 사용하기 위해 보존한다.
   // 인에이블: ir_write = 1일 때만 갱신 (IF 단계)
   //           이후 사이클에서는 ir_write = 0 → 명령어 유지
   // 리셋값: NOP (ADDI x0, x0, 0 = 32'h0000_0013)
   // =========================================================================
   always_ff @(posedge clk or negedge rst_n) begin
      if (!rst_n)
         ir_reg <= 32'h0000_0013;      // 리셋 시 NOP 명령어
      else if (ir_write)
         ir_reg <= mem_data_out;        // IF 단계: 인출된 명령어 래치
      // ir_write = 0이면 ir_reg 값 유지 (암묵적 래치가 아닌 레지스터 유지)
   end

   // =========================================================================
   // 2. 메모리 데이터 레지스터 (MDR — Memory Data Register)
   // =========================================================================
   // 역할: MEM 단계에서 메모리가 반환한 로드 데이터를 WB 단계까지 보존한다.
   //       동기 메모리는 데이터가 다음 사이클에 유효하므로,
   //       MDR 없이는 WB 단계에서 데이터를 사용할 수 없다.
   // 인에이블: 매 사이클 무조건 갱신 (인에이블 신호 불필요)
   //           MEM 단계 이외 사이클에서는 MDR 값을 사용하지 않으므로 무해함
   // =========================================================================
   always_ff @(posedge clk) begin
      mdr_reg <= mem_data_out;          // 매 클럭 에지에 메모리 출력 래치
   end

   // =========================================================================
   // 3. A 레지스터 (rs1 임시 저장)
   // =========================================================================
   // 역할: ID 단계에서 레지스터 파일을 읽은 rs1 데이터를 EX 단계까지 보존한다.
   //       EX 단계에서 ALU 입력 A로 사용된다.
   // 인에이블: 매 사이클 무조건 갱신 (ID 단계 이후 값이 EX에서 필요)
   // =========================================================================
   always_ff @(posedge clk or negedge rst_n) begin
      if (!rst_n)
         a_reg <= 32'd0;               // 리셋 시 0
      else
         a_reg <= rs1_data;            // ID 단계: rs1 데이터 래치
   end

   // =========================================================================
   // 4. B 레지스터 (rs2 임시 저장)
   // =========================================================================
   // 역할: ID 단계에서 레지스터 파일을 읽은 rs2 데이터를 EX/MEM 단계까지 보존한다.
   //       R-type 명령어의 ALU 입력 B, 또는 SW 명령어의 쓰기 데이터로 사용된다.
   // 인에이블: 매 사이클 무조건 갱신
   // =========================================================================
   always_ff @(posedge clk or negedge rst_n) begin
      if (!rst_n)
         b_reg <= 32'd0;               // 리셋 시 0
      else
         b_reg <= rs2_data;            // ID 단계: rs2 데이터 래치
   end

endmodule
