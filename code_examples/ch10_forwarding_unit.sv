// ============================================================================
// 포워딩 유닛 (Forwarding Unit)
// Chapter 10 — 데이터 해저드와 포워딩
// RISC-V 프로세서 설계 완전정복
// ============================================================================
// EX-EX 포워딩과 MEM-EX 포워딩을 감지하여 MUX 선택 신호 생성
// 포워딩 우선순위: EX-EX > MEM-EX > 레지스터 파일 값
// x0 포워딩 방지: rd != 0 조건 포함
// ============================================================================

`timescale 1ns / 1ps

module forwarding_unit (
   // --- EX 스테이지의 소스 레지스터 ---
   input  logic [4:0] id_ex_rs1,        // ID/EX 파이프라인 레지스터의 rs1
   input  logic [4:0] id_ex_rs2,        // ID/EX 파이프라인 레지스터의 rs2

   // --- EX/MEM 스테이지 결과 (1사이클 전 명령어) ---
   input  logic       ex_mem_reg_w_en,  // EX/MEM: 레지스터 쓰기 인에이블
   input  logic [4:0] ex_mem_rd,        // EX/MEM: 목적지 레지스터 번호

   // --- MEM/WB 스테이지 결과 (2사이클 전 명령어) ---
   input  logic       mem_wb_reg_w_en,  // MEM/WB: 레지스터 쓰기 인에이블
   input  logic [4:0] mem_wb_rd,        // MEM/WB: 목적지 레지스터 번호

   // --- 포워딩 MUX 선택 신호 ---
   output logic [1:0] fwd_a,            // ALU 오퍼랜드 A 선택
   output logic [1:0] fwd_b             // ALU 오퍼랜드 B 선택
);

   // =======================================================================
   // 포워딩 MUX 인코딩
   // =======================================================================
   // fwd_a / fwd_b 값:
   //   2'b00 = 레지스터 파일 값 사용 (포워딩 없음)
   //   2'b10 = EX-EX 포워딩 (EX/MEM 파이프라인 레지스터에서)
   //   2'b01 = MEM-EX 포워딩 (MEM/WB 파이프라인 레지스터에서)

   // =======================================================================
   // 오퍼랜드 A 포워딩 로직
   // =======================================================================
   always_comb begin
      // 기본값: 포워딩 없음 (레지스터 파일 값 사용)
      fwd_a = 2'b00;

      // EX-EX 포워딩 (최우선순위)
      // 조건: 1사이클 전 명령어가 레지스터에 쓰고,
      //       그 목적지가 x0이 아니며,
      //       현재 명령어의 rs1과 일치
      if (ex_mem_reg_w_en && (ex_mem_rd != 5'b0) &&
          (ex_mem_rd == id_ex_rs1)) begin
         fwd_a = 2'b10;
      end
      // MEM-EX 포워딩 (차순위)
      // 조건: 2사이클 전 명령어가 레지스터에 쓰고,
      //       그 목적지가 x0이 아니며,
      //       현재 명령어의 rs1과 일치하고,
      //       EX-EX 포워딩이 적용되지 않는 경우
      else if (mem_wb_reg_w_en && (mem_wb_rd != 5'b0) &&
               (mem_wb_rd == id_ex_rs1)) begin
         fwd_a = 2'b01;
      end
   end

   // =======================================================================
   // 오퍼랜드 B 포워딩 로직
   // =======================================================================
   always_comb begin
      // 기본값: 포워딩 없음
      fwd_b = 2'b00;

      // EX-EX 포워딩 (최우선순위)
      if (ex_mem_reg_w_en && (ex_mem_rd != 5'b0) &&
          (ex_mem_rd == id_ex_rs2)) begin
         fwd_b = 2'b10;
      end
      // MEM-EX 포워딩 (차순위)
      else if (mem_wb_reg_w_en && (mem_wb_rd != 5'b0) &&
               (mem_wb_rd == id_ex_rs2)) begin
         fwd_b = 2'b01;
      end
   end

endmodule
