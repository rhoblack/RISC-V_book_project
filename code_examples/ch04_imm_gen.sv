// =============================================================================
// 모듈명: imm_gen
// 설  명: RV32I 즉치수 생성기 — 6가지 명령어 타입별 즉치수 추출 및 부호 확장
// 파  일: ch04_imm_gen.sv
// 표  준: IEEE 1800-2017 (SystemVerilog)
// 저  자: RISC-V 프로세서 설계 완전정복 — Chapter 04
// =============================================================================
// 즉치수 선택 코드 (imm_sel[2:0]):
//   3'b000 : I 타입 (ADDI, LW, JALR 등)       — 12비트 부호 확장
//   3'b001 : S 타입 (SW, SH, SB)               — 12비트 부호 확장
//   3'b010 : B 타입 (BEQ, BNE 등)              — 13비트 부호 확장, LSB=0
//   3'b011 : U 타입 (LUI, AUIPC)               — 상위 20비트 배치
//   3'b100 : J 타입 (JAL)                       — 21비트 부호 확장, LSB=0
//   3'b101 : R 타입 (즉치수 없음)               — 32'b0 출력
// =============================================================================

module imm_gen (
   input  logic [31:0] inst,        // 32비트 명령어 전체
   input  logic [2:0]  imm_sel,     // 즉치수 타입 선택 (제어 유닛에서 생성)
   output logic [31:0] imm_out      // 32비트 부호 확장된 즉치수
);

   always_comb begin
      case (imm_sel)
         // ---------------------------------------------------------------
         // I 타입: imm[11:0] = inst[31:20]
         // 예: ADDI, ANDI, ORI, XORI, SLTI, SLTIU, LW, LH, LB, JALR
         // ---------------------------------------------------------------
         3'b000: imm_out = {{20{inst[31]}}, inst[31:20]};

         // ---------------------------------------------------------------
         // S 타입: imm[11:5] = inst[31:25], imm[4:0] = inst[11:7]
         // 예: SW, SH, SB
         // ---------------------------------------------------------------
         3'b001: imm_out = {{20{inst[31]}}, inst[31:25], inst[11:7]};

         // ---------------------------------------------------------------
         // B 타입: imm[12|10:5|4:1|11] — 주의: 비트 재배열 발생!
         // imm[0] = 0 (항상, 2바이트 정렬)
         // 예: BEQ, BNE, BLT, BGE, BLTU, BGEU
         // ---------------------------------------------------------------
         3'b010: imm_out = {{19{inst[31]}}, inst[31], inst[7],
                            inst[30:25], inst[11:8], 1'b0};

         // ---------------------------------------------------------------
         // U 타입: imm[31:12] = inst[31:12], imm[11:0] = 0
         // 예: LUI, AUIPC
         // ---------------------------------------------------------------
         3'b011: imm_out = {inst[31:12], 12'b0};

         // ---------------------------------------------------------------
         // J 타입: imm[20|10:1|11|19:12] — 주의: 비트 재배열 발생!
         // imm[0] = 0 (항상, 2바이트 정렬)
         // 예: JAL
         // ---------------------------------------------------------------
         3'b100: imm_out = {{11{inst[31]}}, inst[31], inst[19:12],
                            inst[20], inst[30:21], 1'b0};

         // ---------------------------------------------------------------
         // R 타입 또는 기본값: 즉치수 없음
         // ---------------------------------------------------------------
         default: imm_out = 32'b0;
      endcase
   end

endmodule
