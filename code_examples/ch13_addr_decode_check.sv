// =============================================================================
// Ch13: 교육용 주소 분해 검증 모듈 (Address Decode Checker)
// 32비트 주소를 Tag / Index / Offset으로 분해하여 화면에 출력
// 시뮬레이션에서 캐시 설계 이해를 돕기 위한 학습 보조 도구
// =============================================================================

`timescale 1ns / 1ps

module ch13_addr_decode_check;

   // =========================================================================
   // 캐시 파라미터 (4KB / 128엔트리 / 32바이트 블록)
   // =========================================================================

   localparam OFFSET_WIDTH = 5;   // log2(32)  = 5비트
   localparam INDEX_WIDTH  = 7;   // log2(128) = 7비트
   localparam TAG_WIDTH    = 20;  // 32 - 5 - 7 = 20비트

   // =========================================================================
   // 함수: 주소 분해 및 출력
   // =========================================================================

   function automatic void decode_addr(
      input  logic [31:0] addr,
      input  string       desc
   );
      logic [TAG_WIDTH-1:0]    tag;
      logic [INDEX_WIDTH-1:0]  index;
      logic [OFFSET_WIDTH-1:0] offset;
      logic [2:0]              word_offset;

      // 필드 추출
      tag         = addr[31:12];   // 상위 20비트
      index       = addr[11:5];    // 중간 7비트
      offset      = addr[4:0];     // 하위 5비트
      word_offset = addr[4:2];     // 워드 선택 (3비트)

      $display("------------------------------------------------------------");
      $display("주소: 0x%08X  (%s)", addr, desc);
      $display("  이진:   %b_%b_%b_%b",
               addr[31:24], addr[23:16], addr[15:8], addr[7:0]);
      $display("  Tag     [31:12] = 0x%05X  (%0d번째 블록 구분자)", tag, tag);
      $display("  Index   [11: 5] = %3d (0x%02X)  → 캐시 엔트리 #%0d 에 저장", index, index, index);
      $display("  Offset  [ 4: 0] = %2d (0x%02X)  → 블록 내 바이트 %0d번째", offset, offset, offset);
      $display("  Wrd_Sel [ 4: 2] = %1d           → 블록 내 워드 %0d번째", word_offset, word_offset);
   endfunction

   // =========================================================================
   // 함수: 두 주소가 같은 캐시 엔트리에 충돌하는지 판정
   // =========================================================================

   function automatic void check_conflict(
      input logic [31:0] addr_a,
      input logic [31:0] addr_b
   );
      logic [INDEX_WIDTH-1:0]  idx_a, idx_b;
      logic [TAG_WIDTH-1:0]    tag_a, tag_b;

      idx_a = addr_a[11:5];
      idx_b = addr_b[11:5];
      tag_a = addr_a[31:12];
      tag_b = addr_b[31:12];

      $display("");
      $display("충돌 분석: 0x%08X vs 0x%08X", addr_a, addr_b);
      if (idx_a == idx_b) begin
         if (tag_a == tag_b) begin
            $display("  → [같은 블록] Tag=0x%05X, Index=%0d: 동일 캐시 라인!", tag_a, idx_a);
         end else begin
            $display("  → [충돌 미스!] Index=%0d로 같음, Tag: 0x%05X vs 0x%05X",
                     idx_a, tag_a, tag_b);
            $display("     직접 매핑에서 번갈아 접근 시 모두 MISS 발생!");
         end
      end else begin
         $display("  → [충돌 없음] Index: %0d vs %0d → 서로 다른 엔트리에 저장",
                  idx_a, idx_b);
      end
   endfunction

   // =========================================================================
   // 메인 시뮬레이션
   // =========================================================================

   initial begin
      $display("============================================================");
      $display("Ch13 교육용 주소 분해 검증 도구");
      $display("캐시 파라미터: 4KB / 128엔트리 / 32바이트 블록");
      $display("Tag[31:12]=20비트 / Index[11:5]=7비트 / Offset[4:0]=5비트");
      $display("============================================================");

      // -------------------------------------------------------
      // 기본 예제: 5개 주소 분해
      // -------------------------------------------------------
      $display("\n[예제 1~5] 기본 주소 분해");

      decode_addr(32'h0000_0000, "예제1: 블록0 기저 주소");
      decode_addr(32'h0000_0004, "예제2: 블록0, 워드1 (예제1과 같은 블록!)");
      decode_addr(32'h0000_0020, "예제3: 블록1 기저 주소 (Index=1)");
      decode_addr(32'h0000_0040, "예제4: 블록2 기저 주소 (Index=2)");
      decode_addr(32'h0001_0000, "예제5: 충돌 주소 (Index=0, Tag 다름!)");

      // -------------------------------------------------------
      // 충돌 분석
      // -------------------------------------------------------
      $display("\n[충돌 분석] 직접 매핑 충돌 패턴 확인");

      check_conflict(32'h0000_0000, 32'h0000_0004);   // 같은 블록 (충돌 없음)
      check_conflict(32'h0000_0000, 32'h0000_0020);   // 다른 블록 (충돌 없음)
      check_conflict(32'h0000_0000, 32'h0001_0000);   // 충돌! (Index=0 공유)
      check_conflict(32'h0000_0020, 32'h0001_0020);   // 충돌! (Index=1 공유)

      // -------------------------------------------------------
      // 연습문제 정답 검증
      // -------------------------------------------------------
      $display("\n[연습문제 정답 검증]");

      $display("\nQ1: 0x0000_0060의 Tag/Index/Offset은?");
      decode_addr(32'h0000_0060, "Q1 정답");

      $display("\nQ2: 0x0000_0000과 충돌하는 주소 하나 더");
      decode_addr(32'h0002_0000, "Q2 예시: 0x0002_0000");
      check_conflict(32'h0000_0000, 32'h0002_0000);

      $display("\nQ3: 블록 크기 64바이트일 때 Offset 비트 폭");
      $display("  log2(64) = 6비트 → Offset[5:0], Index[12:6], Tag[31:13]");
      $display("  Index 비트: log2(4096/64) = log2(64) = 6비트");
      $display("  Tag 비트: 32 - 6 - 6 = 20비트 (동일!)");

      $display("\n============================================================");
      $display("주소 분해 검증 완료.");
      $display("============================================================");

      $finish;
   end

endmodule
