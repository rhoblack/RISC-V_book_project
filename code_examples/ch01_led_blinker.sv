// ============================================================================
// 모듈명  : led_blinker
// 파일명  : ch01_led_blinker.sv
// 설명    : Basys 3 FPGA 보드에서 LED를 1Hz 주기로 점멸하는 모듈
//           100MHz 시스템 클록을 분주하여 사람이 인식할 수 있는 속도로 LED 제어
// 대상 보드: Digilent Basys 3 (Artix-7 XC7A35T)
// 작성 기준: SystemVerilog IEEE 1800-2017
// ============================================================================

module led_blinker (
   input  logic       clk,      // 100MHz 시스템 클록 (Basys 3 W5 핀)
   input  logic       rst_n,    // 능동 저(Active-Low) 리셋 (Basys 3 센터 버튼)
   output logic [3:0] led       // LED 출력 (Basys 3 U16, E19, U19, V19 핀)
);

   // -----------------------------------------------------------------------
   // 파라미터 정의
   // -----------------------------------------------------------------------
   // 100MHz 클록에서 1초 = 100,000,000 사이클
   // 0.5초마다 토글하려면 50,000,000 사이클 카운트
   localparam int unsigned MAX_COUNT = 50_000_000 - 1;

   // 시뮬레이션 시 빠른 확인을 위한 조건부 파라미터
   // synthesis translate_off
   // localparam int unsigned MAX_COUNT = 5 - 1;  // 시뮬레이션용
   // synthesis translate_on

   // -----------------------------------------------------------------------
   // 내부 신호 선언
   // -----------------------------------------------------------------------
   logic [25:0] counter;     // 26비트 카운터 (최대 67,108,863까지 카운트 가능)
   logic        tick;        // 0.5초마다 발생하는 틱 신호
   logic [3:0]  led_pattern; // LED 패턴 레지스터

   // -----------------------------------------------------------------------
   // 카운터 로직: 0.5초마다 틱 신호 생성
   // -----------------------------------------------------------------------
   always_ff @(posedge clk or negedge rst_n) begin
      if (!rst_n) begin
         counter <= '0;
      end else if (counter == MAX_COUNT[25:0]) begin
         counter <= '0;
      end else begin
         counter <= counter + 1'b1;
      end
   end

   // 틱 신호 생성 (조합 논리)
   always_comb begin
      tick = (counter == MAX_COUNT[25:0]);
   end

   // -----------------------------------------------------------------------
   // LED 패턴 생성: 틱마다 패턴 순환
   // -----------------------------------------------------------------------
   // 패턴 순서: 0001 → 0010 → 0100 → 1000 → 0001 (시프트 레지스터)
   always_ff @(posedge clk or negedge rst_n) begin
      if (!rst_n) begin
         led_pattern <= 4'b0001;  // 초기값: 첫 번째 LED만 점등
      end else if (tick) begin
         led_pattern <= {led_pattern[2:0], led_pattern[3]};  // 좌측 순환 시프트
      end
   end

   // -----------------------------------------------------------------------
   // 출력 연결
   // -----------------------------------------------------------------------
   assign led = led_pattern;

endmodule
